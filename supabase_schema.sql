-- ============================================================
-- KR8 DIGITALS — DEPRECATED SCHEMA FILE
-- ============================================================
-- This file used to create the legacy schema with PUBLIC select/insert/update
-- policies on `accounts` (plaintext passwords, phone numbers, emails and
-- dates of birth). Those policies exposed every student record to anyone with
-- the public API key and have been REMOVED from this repository.
--
-- The secure, authoritative schema now lives in /migrations:
--
--   migrations/0001_lockdown_legacy_policies.sql
--       Drops every legacy public policy and enables RLS (default deny) on
--       the old tables: accounts, attendances, live_streams, live_chat,
--       stream_replays, feed_items, streams, stream_*.
--
--   migrations/0002_core_tables.sql
--       Creates (if missing) the core tables used by the secure app:
--       profiles, user_roles, certificates, attendance_submissions,
--       enrollments, notifications, announcements, testimonials,
--       site_content, site_settings, skill_settings, team_members,
--       activity_log, email_logs — and adds the `extra jsonb` column used for
--       legacy-shaped fields. Additive only; never overwrites data.
--
--   migrations/0003_live_tables.sql
--       live_rooms, room_admissions, room_messages, recordings.
--
--   migrations/0004_functions.sql
--       get_unified_leaderboard(p_limit)  — public leaderboard (safe fields)
--       next_kr8_serial(p_skill)          — server-only KR8 ID allocation
--
--   migrations/0005_rls_policies.sql
--       Secure Row Level Security for every table: students see only their
--       own profile row; verification/leaderboard expose only safe fields;
--       all writes go through server functions that check `user_roles`.
--
--   migrations/0006_social_mindset.sql
--       password_reset_codes (server-only, hashed codes), blog_comments,
--       blog_post_likes, gallery_items, client_requests, video_comments,
--       messages, user_follows, mindset_events, mindset_registrations.
--
-- Apply them in numeric order in the Supabase SQL editor. Do NOT run any
-- legacy schema that contains `create policy ... using (true)` on accounts.
--
-- Authentication is Supabase Auth (email + password) only. The old plaintext
-- `accounts.password` column is no longer read, written or compared by any
-- code in this repository.
-- ============================================================
